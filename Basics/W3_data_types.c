#include <stdio.h>

int main() {
    int myNum = 5;
    float myFloatNum = 5.99;
    double myDouble = 3.14159265359;
    char myLetter = 'D';

    printf("int: %d\n", myNum);
    printf("float: %f\n", myFloatNum);
    printf("double: %lf\n", myDouble);
    printf("char: %c\n", myLetter);
    return 0;
}
